    public func applyModeSelection(mode: CleanerMode) {
        self.selectedMode = mode
        for i in 0..<categories.count {
            switch mode {
            case .quick:
                categories[i].isSelected = (categories[i].safety == .safe)
            case .developer:
                categories[i].isSelected = (categories[i].safety == .safe || categories[i].group == .developer || categories[i].group == .packageManagers)
            case .custom:
                break // Keep current manual selections
            }
        }
    }
    
    // MARK: - Scan
    public func scanAll() {
        guard !isScanning else { return }
        isScanning = true
        scanProgress = 0.0
        currentActionText = "Starting system storage audit..."
        refreshDiskSpace()
        
        let cats = categories
        
        scanTask = Task.detached(priority: .userInitiated) { [weak self] in
            guard let self = self else { return }
            
            var scannedList: [SystemCleanupCategoryItem] = []
            let total = Double(max(1, cats.count))
            
            for (idx, cat) in cats.enumerated() {
                if Task.isCancelled { break }
                
                await MainActor.run {
                    self.currentActionText = "Scanning \(cat.name)..."
                    self.scanProgress = Double(idx) / total
                }
                
                let scannedCat = Self.measureCategory(cat: cat)
                scannedList.append(scannedCat)
            }
            
            await MainActor.run {
                self.categories = scannedList
                self.isScanning = false
                self.scanProgress = 1.0
                let totalFreed = scannedList.reduce(0) { $0 + $1.estimatedSizeBytes }
                self.currentActionText = "Scan completed. Found \(Formatters.bytes(totalFreed)) potential reclaimable space."
            }
        }
    }
    
    public func cancelScan() {
        scanTask?.cancel()
        scanTask = nil
        isScanning = false
        currentActionText = "Scan cancelled."
    }
    
    public nonisolated static func measureCategory(cat: SystemCleanupCategoryItem) -> SystemCleanupCategoryItem {
        let fileManager = FileManager.default
        let path = cat.path
        
        guard fileManager.fileExists(atPath: path) else {
            var empty = cat
            empty.estimatedSizeBytes = 0
            empty.fileCount = 0
            empty.files = []
            return empty
        }
        
        let url = URL(fileURLWithPath: path, isDirectory: true)
        let keys: Set<URLResourceKey> = [.fileSizeKey, .contentModificationDateKey, .isRegularFileKey]
        
        var totalSize: UInt64 = 0
        var files: [CleanupFileItem] = []
        var count = 0
        
        if let enumerator = fileManager.enumerator(
            at: url,
            includingPropertiesForKeys: Array(keys),
            options: [.skipsHiddenFiles, .skipsPackageDescendants]
        ) {
            while let itemURL = enumerator.nextObject() as? URL {
                if Task.isCancelled { break }
                guard let vals = try? itemURL.resourceValues(forKeys: keys) else { continue }
                
                if vals.isRegularFile ?? false {
                    let s = UInt64(vals.fileSize ?? 0)
                    totalSize += s
                    count += 1
                    
                    if files.count < 300 {
                        files.append(CleanupFileItem(
                            path: itemURL.path,
                            name: itemURL.lastPathComponent,
                            sizeBytes: s,
                            modifiedDate: vals.contentModificationDate,
                            isSafe: cat.safety == .safe
                        ))
                    }
                }
            }
        }
        
        var updated = cat
        updated.estimatedSizeBytes = totalSize
        updated.fileCount = count
        updated.files = files
        return updated
    }
    
    // MARK: - Execute Clean
    public func executeClean(dryRun: Bool = false) {
        guard !isCleaning else { return }
        isCleaning = true
        cleanProgress = 0.0
        currentActionText = dryRun ? "Simulating cleanup (dry-run)..." : "Cleaning selected categories..."
        
        let startTime = Date()
        let selectedCats = categories.filter { $0.isSelected }
        
        cleanTask = Task.detached(priority: .userInitiated) { [weak self] in
            guard let self = self else { return }
            
            let fileManager = FileManager.default
            var freed: UInt64 = 0
            var deletedCount = 0
            var failCount = 0
            var errors: [String] = []
            
            let totalCats = Double(max(1, selectedCats.count))
            
            for (idx, cat) in selectedCats.enumerated() {
                if Task.isCancelled { break }
                
                await MainActor.run {
                    self.currentActionText = "Purging \(cat.name)..."
                    self.cleanProgress = Double(idx) / totalCats
                }
                
                if dryRun {
                    freed += cat.estimatedSizeBytes
                    deletedCount += cat.fileCount
                    continue
                }
                
                let dirURL = URL(fileURLWithPath: cat.path, isDirectory: true)
                guard fileManager.fileExists(atPath: cat.path) else { continue }
                
                // Remove individual items inside the folder rather than deleting the root directory
                if let subItems = try? fileManager.contentsOfDirectory(at: dirURL, includingPropertiesForKeys: nil) {
                    for item in subItems {
                        if Task.isCancelled { break }
                        do {
                            let size = (try? fileManager.attributesOfItem(atPath: item.path)[.size] as? UInt64) ?? 0
                            try fileManager.removeItem(at: item)
                            freed += size
                            deletedCount += 1
                        } catch {
                            failCount += 1
                            errors.append("Failed removing \(item.lastPathComponent): \(error.localizedDescription)")
                        }
                    }
                }
            }
            
            let duration = Date().timeIntervalSince(startTime)
            let report = CleanerExecutionReport(
                bytesFreed: freed,
                itemsRemoved: deletedCount,
                failuresCount: failCount,
                errors: errors,
                durationSeconds: duration
            )
            
            await MainActor.run {
                self.lastReport = report
                self.isCleaning = false
                self.cleanProgress = 1.0
                self.currentActionText = dryRun
                    ? "Dry run complete: \(Formatters.bytes(freed)) eligible."
                    : "Clean complete: \(Formatters.bytes(freed)) reclaimed."
                self.refreshDiskSpace()
                if !dryRun {
                    self.scanAll()
                }
            }
        }
    }
    
    public func toggleCategory(id: String) {
        if let idx = categories.firstIndex(where: { $0.id == id }) {
            categories[idx].isSelected.toggle()
        }
    }
}
