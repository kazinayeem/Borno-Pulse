import Foundation
import Combine

@MainActor
public final class SystemCleanerService: ObservableObject {
    public static let shared = SystemCleanerService()
    
    @Published public var diskSpace: DiskVolumeSpace = DiskVolumeSpace()
    @Published public var categories: [SystemCleanupCategoryItem] = []
    @Published public var selectedMode: CleanerMode = .quick
    @Published public var isScanning: Bool = false
    @Published public var isCleaning: Bool = false
    @Published public var scanProgress: Double = 0.0
    @Published public var cleanProgress: Double = 0.0
    @Published public var currentActionText: String = ""
    @Published public var lastReport: CleanerExecutionReport? = nil
    
    private var scanTask: Task<Void, Never>?
    private var cleanTask: Task<Void, Never>?
    
    public var totalReclaimableBytes: UInt64 {
        categories.reduce(0) { $0 + $1.estimatedSizeBytes }
    }
    
    public var selectedReclaimableBytes: UInt64 {
        categories.filter { $0.isSelected }.reduce(0) { $0 + $1.estimatedSizeBytes }
    }
    
    private init() {
        refreshDiskSpace()
        setupCategories()
    }
    
    public func refreshDiskSpace() {
        let rootURL = URL(fileURLWithPath: "/")
        do {
            let values = try rootURL.resourceValues(forKeys: [
                .volumeTotalCapacityKey,
                .volumeAvailableCapacityKey,
                .volumeAvailableCapacityForImportantUsageKey
            ])
            let total = UInt64(values.volumeTotalCapacity ?? 0)
            let avail = UInt64(values.volumeAvailableCapacity ?? 0)
            let used = total > avail ? (total - avail) : 0
            
            self.diskSpace = DiskVolumeSpace(
                totalCapacityBytes: total,
                availableBytes: avail,
                usedBytes: used,
                purgeableBytes: 0
            )
        } catch {
            self.diskSpace = DiskVolumeSpace()
        }
    }
    
