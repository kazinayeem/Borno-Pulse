//
//  ClipboardManagerService.swift
//  Borno Pulse
//
//  Single source of truth for clipboard history, shared by the Clipboard Manager page,
//  the ⌘B picker and the menu bar. Monitoring is opt-in, local-only and runs
//  independently of any window.
//
//  Detection limits: macOS does not tell an app which field or process produced a
//  pasteboard change. Sensitive content is skipped when the source app marks it as
//  concealed/transient (nspasteboard.org conventions), when the frontmost app is
//  excluded, or when text matches common secret patterns. Content from apps that do
//  none of these cannot be recognised as sensitive reliably.
//

import AppKit
import Combine
import Foundation

public struct ClipboardServiceEnvironment {
    public var pasteboard: NSPasteboard
    public var defaults: UserDefaults
    public var storageRoot: URL
    public var frontmostApp: @MainActor () -> ClipboardSourceApp?
    public var now: () -> Date
    /// When false, no polling timer is scheduled (tests call `captureIfChanged()` directly).
    public var usesTimers: Bool

    public init(
        pasteboard: NSPasteboard,
        defaults: UserDefaults,
        storageRoot: URL,
        frontmostApp: @escaping @MainActor () -> ClipboardSourceApp?,
        now: @escaping () -> Date = Date.init,
        usesTimers: Bool
    ) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.storageRoot = storageRoot
        self.frontmostApp = frontmostApp
        self.now = now
        self.usesTimers = usesTimers
    }

    @MainActor
    public static var live: ClipboardServiceEnvironment {
        ClipboardServiceEnvironment(
            pasteboard: .general,
            defaults: .standard,
            storageRoot: ClipboardStorage.defaultRoot,
            frontmostApp: {
                let app = NSWorkspace.shared.frontmostApplication
                return app.map { ClipboardSourceApp(name: $0.localizedName, bundleID: $0.bundleIdentifier) }
            },
            usesTimers: true
        )
    }
}

public enum ClipboardCaptureResult: Equatable, Sendable {
    case captured(ClipboardItem)
    /// Content already in history; moved to the top instead of duplicated.
    case refreshed(ClipboardItem)
    case skipped(ClipboardSkipReason)
}

@MainActor
public final class ClipboardManagerService: ObservableObject {
    public static let shared = ClipboardManagerService(environment: .live)

    enum Keys {
        static let isEnabled = "Clipboard_IsEnabled"
        static let isPaused = "Clipboard_IsPaused"
        static let pausedUntil = "Clipboard_PausedUntil"
        static let excludedBundles = "Clipboard_ExcludedBundles"
        static let filterSensitive = "Clipboard_FilterSensitive"
        static let maxItems = "Clipboard_MaxItems"
        static let retentionDays = "Clipboard_RetentionDays"
        static let maxItemSizeMB = "Clipboard_MaxItemSizeMB"
        static let imageStorageLimitMB = "Clipboard_ImageStorageLimitMB"
        static let autoPaste = "Clipboard_AutoPaste"
        static let shortcutEnabled = "Clipboard_ShortcutEnabled"
        static let shortcut = "Clipboard_Shortcut"
        static let showMenuBarIcon = "Clipboard_ShowMenuBarIcon"
        static let settingsVersion = "Clipboard_SettingsVersion"
    }

    static let currentSettingsVersion = 2

    public static let defaultExcludedBundleIDs: Set<String> = [
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords"
    ]

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let onePasswordType = NSPasteboard.PasteboardType("com.agilebits.onepassword")

    // MARK: - Published State

    @Published public var isEnabled: Bool {
        didSet {
            guard isEnabled != oldValue else { return }
            defaults.set(isEnabled, forKey: Keys.isEnabled)
            if isEnabled { startMonitoring() } else { stopMonitoring() }
        }
    }

    @Published public private(set) var isPaused: Bool
    @Published public private(set) var pausedUntil: Date?
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public private(set) var hasLoadedHistory = false
    @Published public private(set) var lastSkipReason: ClipboardSkipReason?

    @Published public var excludedBundleIDs: Set<String> {
        didSet {
            if let data = try? JSONEncoder().encode(Array(excludedBundleIDs).sorted()) {
                defaults.set(data, forKey: Keys.excludedBundles)
            }
        }
    }

    @Published public var filterSensitive: Bool {
        didSet { defaults.set(filterSensitive, forKey: Keys.filterSensitive) }
    }

    @Published public var maxItemsCount: Int {
        didSet {
            defaults.set(maxItemsCount, forKey: Keys.maxItems)
            applyLimitsAndSave()
        }
    }

    @Published public var retention: ClipboardRetention {
        didSet {
            defaults.set(retention.rawValue, forKey: Keys.retentionDays)
            applyLimitsAndSave()
        }
    }

    @Published public var maxItemSizeMB: Int {
        didSet { defaults.set(maxItemSizeMB, forKey: Keys.maxItemSizeMB) }
    }

    @Published public var imageStorageLimitMB: Int {
        didSet {
            defaults.set(imageStorageLimitMB, forKey: Keys.imageStorageLimitMB)
            applyLimitsAndSave()
        }
    }

    @Published public var autoPasteEnabled: Bool {
        didSet { defaults.set(autoPasteEnabled, forKey: Keys.autoPaste) }
    }

    @Published public var shortcutEnabled: Bool {
        didSet { defaults.set(shortcutEnabled, forKey: Keys.shortcutEnabled) }
    }

    @Published public var shortcut: KeyboardShortcutSpec {
        didSet {
            if let data = try? JSONEncoder().encode(shortcut) {
                defaults.set(data, forKey: Keys.shortcut)
            }
        }
    }

    @Published public var showMenuBarIcon: Bool {
        didSet { defaults.set(showMenuBarIcon, forKey: Keys.showMenuBarIcon) }
    }

    public var monitoringState: ClipboardMonitoringState {
        if !isEnabled { return .off }
        if isPaused { return .paused(until: pausedUntil) }
        return .monitoring
    }

    /// True while the change-count timer is scheduled.
    public var isPolling: Bool { pollTimer != nil }

    // MARK: - Internals

    public let storage: ClipboardStorage
    private let environment: ClipboardServiceEnvironment
    private var defaults: UserDefaults { environment.defaults }
    private var pasteboard: NSPasteboard { environment.pasteboard }
    private var pollTimer: Timer?
    private var resumeTimer: Timer?
    private var lastChangeCount: Int

    public static let pollInterval: TimeInterval = 0.5

    public init(environment: ClipboardServiceEnvironment) {
        self.environment = environment
        let defaults = environment.defaults
        Self.migrateSettings(in: defaults)

        storage = ClipboardStorage(rootDirectory: environment.storageRoot)
        lastChangeCount = environment.pasteboard.changeCount

        isEnabled = defaults.bool(forKey: Keys.isEnabled)
        isPaused = defaults.bool(forKey: Keys.isPaused)
        let untilInterval = defaults.double(forKey: Keys.pausedUntil)
        pausedUntil = untilInterval > 0 ? Date(timeIntervalSince1970: untilInterval) : nil
        filterSensitive = defaults.object(forKey: Keys.filterSensitive) as? Bool ?? true
        let savedMax = defaults.integer(forKey: Keys.maxItems)
        maxItemsCount = savedMax > 0 ? savedMax : 100
        retention = ClipboardRetention(rawValue: defaults.object(forKey: Keys.retentionDays) as? Int ?? 30) ?? .oneMonth
        let savedItemSize = defaults.integer(forKey: Keys.maxItemSizeMB)
        maxItemSizeMB = savedItemSize > 0 ? savedItemSize : 10
        let savedImageLimit = defaults.integer(forKey: Keys.imageStorageLimitMB)
        imageStorageLimitMB = savedImageLimit > 0 ? savedImageLimit : 250
        autoPasteEnabled = defaults.object(forKey: Keys.autoPaste) as? Bool ?? true
        shortcutEnabled = defaults.object(forKey: Keys.shortcutEnabled) as? Bool ?? true
        if let data = defaults.data(forKey: Keys.shortcut),
           let spec = try? JSONDecoder().decode(KeyboardShortcutSpec.self, from: data) {
            shortcut = spec
        } else {
            shortcut = .commandB
        }
        showMenuBarIcon = defaults.object(forKey: Keys.showMenuBarIcon) as? Bool ?? true

        if let data = defaults.data(forKey: Keys.excludedBundles),
           let arr = try? JSONDecoder().decode([String].self, from: data) {
            excludedBundleIDs = Set(arr)
        } else {
            excludedBundleIDs = Self.defaultExcludedBundleIDs
        }

        loadHistory()

        if isPaused, let until = pausedUntil, until <= environment.now() {
            setPaused(false, until: nil)
        }
        if isEnabled {
            startMonitoring()
        }
    }

    /// Version 1 stored no retention; keep existing histories intact rather than pruning them on upgrade.
    static func migrateSettings(in defaults: UserDefaults) {
        let version = defaults.integer(forKey: Keys.settingsVersion)
        guard version < currentSettingsVersion else { return }
        let isExistingUser = defaults.object(forKey: Keys.isEnabled) != nil
        if isExistingUser, defaults.object(forKey: Keys.retentionDays) == nil {
            defaults.set(ClipboardRetention.forever.rawValue, forKey: Keys.retentionDays)
        }
        defaults.set(currentSettingsVersion, forKey: Keys.settingsVersion)
    }

    // MARK: - Monitoring Controls

    public func startMonitoring() {
        guard isEnabled, !isPaused else { return }
        guard pollTimer == nil else { return }
        // Only content copied after monitoring starts is recorded.
        lastChangeCount = pasteboard.changeCount
        guard environment.usesTimers else { return }
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { _ = self?.captureIfChanged() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
    }

    public func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
        saveHistory()
    }

    public func pause() {
        pause(for: .untilResumed)
    }

    public func pause(for duration: ClipboardPauseDuration) {
        let until = duration.seconds.map { environment.now().addingTimeInterval($0) }
        setPaused(true, until: until)
        pollTimer?.invalidate()
        pollTimer = nil
        scheduleAutoResume()
    }

    public func resume() {
        setPaused(false, until: nil)
        // Content copied while paused is intentionally not recorded.
        lastChangeCount = pasteboard.changeCount
        startMonitoring()
    }

    public func togglePause() {
        isPaused ? resume() : pause()
    }

    /// Stops all timers and flushes history. Called when the app quits.
    public func shutdown() {
        resumeTimer?.invalidate()
        resumeTimer = nil
        stopMonitoring()
    }

    private func setPaused(_ paused: Bool, until: Date?) {
        isPaused = paused
        pausedUntil = paused ? until : nil
        defaults.set(paused, forKey: Keys.isPaused)
        if let until = pausedUntil {
            defaults.set(until.timeIntervalSince1970, forKey: Keys.pausedUntil)
        } else {
            defaults.removeObject(forKey: Keys.pausedUntil)
        }
        if !paused {
            resumeTimer?.invalidate()
            resumeTimer = nil
        }
    }

    private func scheduleAutoResume() {
        resumeTimer?.invalidate()
        resumeTimer = nil
        guard environment.usesTimers, let until = pausedUntil else { return }
        let timer = Timer(fire: until, interval: 0, repeats: false) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self, self.isPaused else { return }
                self.resume()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        resumeTimer = timer
    }

    // MARK: - Capture

    /// Reads the pasteboard only when monitoring is active and its change count moved.
    @discardableResult
    public func captureIfChanged() -> ClipboardCaptureResult {
        let result = performCapture()
        if case .skipped(let reason) = result {
            if reason != .unchanged { lastSkipReason = reason }
        } else {
            lastSkipReason = nil
        }
        return result
    }

    private func performCapture() -> ClipboardCaptureResult {
        guard isEnabled else { return .skipped(.disabled) }
        if isPaused {
            if let until = pausedUntil, until <= environment.now() {
                resume()
            } else {
                return .skipped(.paused)
            }
        }

        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return .skipped(.unchanged) }
        lastChangeCount = count

        let types = Set(pasteboard.types ?? [])
        if types.contains(Self.transientType) || types.contains(Self.autoGeneratedType) {
            return .skipped(.transientContent)
        }
        if filterSensitive, types.contains(Self.concealedType) || types.contains(Self.onePasswordType) {
            return .skipped(.concealedContent)
        }
        let source = environment.frontmostApp()
        if let bundleID = source?.bundleID, excludedBundleIDs.contains(bundleID) {
            return .skipped(.excludedApplication)
        }

        switch buildItem(types: types, source: source) {
        case .success(let item):
            return insert(item)
        case .failure(let failure):
            return .skipped(failure.reason)
        }
    }

    private struct CaptureFailure: Error {
        let reason: ClipboardSkipReason
    }

    private var maxItemBytes: Int { maxItemSizeMB * 1_048_576 }

    private func buildItem(types: Set<NSPasteboard.PasteboardType>, source: ClipboardSourceApp?) -> Result<ClipboardItem, CaptureFailure> {
        let now = environment.now()

        // 1. File references (Finder copies). Web URLs are excluded by `urlReadingFileURLsOnly`.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            let size = paths.reduce(Int64(0)) { total, path in
                let bytes = (try? FileManager.default.attributesOfItem(atPath: path)[.size] as? NSNumber)?.int64Value ?? 0
                return total + bytes
            }
            return .success(ClipboardItem(
                timestamp: now,
                type: .file,
                preview: urls.map(\.lastPathComponent).joined(separator: ", "),
                filePaths: paths,
                byteSize: size,
                sourceAppName: source?.name,
                sourceBundleID: source?.bundleID,
                contentHash: ClipboardItem.hash(type: .file, parts: paths.map { Data($0.utf8) })
            ))
        }

        // 2. Text, web URLs and rich text.
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isSensitive = Self.detectSensitive(text: trimmed)
            if isSensitive && filterSensitive {
                return .failure(CaptureFailure(reason: .sensitiveContent))
            }
            let rtf = types.contains(.rtf) ? pasteboard.data(forType: .rtf) : nil
            let textBytes = string.utf8.count
            guard textBytes <= maxItemBytes else {
                return .failure(CaptureFailure(reason: .tooLarge))
            }
            // Oversized RTF falls back to plain text rather than dropping the copy.
            let keepRTF = rtf.map { textBytes + $0.count <= maxItemBytes } ?? false

            let type: ClipboardContentType
            if Self.isWebURL(trimmed) {
                type = .url
            } else if keepRTF {
                type = .richText
            } else {
                type = .text
            }
            let storedRTF = type == .richText ? rtf : nil
            var hashParts = [Data(string.utf8)]
            if let storedRTF { hashParts.append(storedRTF) }
            let preview = String(trimmed.prefix(160))
                .replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\t", with: " ")

            return .success(ClipboardItem(
                timestamp: now,
                type: type,
                preview: preview,
                contentText: string,
                isSensitive: isSensitive,
                byteSize: Int64(textBytes + (storedRTF?.count ?? 0)),
                sourceAppName: source?.name,
                sourceBundleID: source?.bundleID,
                rtfData: storedRTF,
                contentHash: ClipboardItem.hash(type: type, parts: hashParts)
            ))
        }

        // 3. Images, normalised to PNG.
        if let png = Self.readPNG(from: pasteboard, types: types) {
            guard png.data.count <= maxItemBytes else {
                return .failure(CaptureFailure(reason: .tooLarge))
            }
            return .success(ClipboardItem(
                timestamp: now,
                type: .image,
                preview: "Image (\(png.width) × \(png.height))",
                imagePNGData: png.data,
                byteSize: Int64(png.data.count),
                sourceAppName: source?.name,
                sourceBundleID: source?.bundleID,
                contentHash: ClipboardItem.hash(type: .image, parts: [png.data])
            ))
        }

        return .failure(CaptureFailure(reason: .unsupportedContent))
    }

    private static func readPNG(from pb: NSPasteboard, types: Set<NSPasteboard.PasteboardType>) -> (data: Data, width: Int, height: Int)? {
        if types.contains(.png), let data = pb.data(forType: .png), let rep = NSBitmapImageRep(data: data) {
            return (data, rep.pixelsWide, rep.pixelsHigh)
        }
        if types.contains(.tiff), let tiff = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        return nil
    }

    nonisolated public static func isWebURL(_ text: String) -> Bool {
        guard text.hasPrefix("http://") || text.hasPrefix("https://"),
              !text.contains(where: \.isWhitespace),
              let url = URL(string: text), url.host?.isEmpty == false else { return false }
        return true
    }

    private func insert(_ newItem: ClipboardItem) -> ClipboardCaptureResult {
        if let hash = newItem.contentHash, let index = items.firstIndex(where: { $0.contentHash == hash }) {
            var existing = items.remove(at: index)
            existing.timestamp = newItem.timestamp
            items.insert(existing, at: 0)
            saveHistory()
            return .refreshed(existing)
        }

        var item = newItem
        if item.type == .image, let png = item.imagePNGData {
            guard let name = storage.writeImage(png, id: item.id) else {
                return .skipped(.unsupportedContent)
            }
            item.imageFileName = name
            item.imagePNGData = nil
        }
        items.insert(item, at: 0)
        applyLimitsAndSave()
        return .captured(item)
    }

    // MARK: - Limits

    private func applyLimitsAndSave() {
        guard hasLoadedHistory else { return }
        applyLimits()
        saveHistory()
    }

    private func applyLimits() {
        var removed: [ClipboardItem] = []

        if let days = retention.days {
            let cutoff = environment.now().addingTimeInterval(-Double(days) * 86_400)
            removed += items.filter { !$0.isPinned && $0.timestamp < cutoff }
            items.removeAll { !$0.isPinned && $0.timestamp < cutoff }
        }

        while items.count > maxItemsCount, let index = items.lastIndex(where: { !$0.isPinned }) {
            removed.append(items.remove(at: index))
        }

        let imageLimit = Int64(imageStorageLimitMB) * 1_048_576
        var imageBytes = items.filter { $0.type == .image }.reduce(Int64(0)) { $0 + $1.byteSize }
        while imageBytes > imageLimit,
              let index = items.lastIndex(where: { $0.type == .image && !$0.isPinned }) {
            let item = items.remove(at: index)
            imageBytes -= item.byteSize
            removed.append(item)
        }

        for item in removed {
            if let name = item.imageFileName { storage.deleteImage(named: name) }
        }
    }

    // MARK: - Actions

    /// Restores the item's original representation to the pasteboard.
    /// Returns false when the content can no longer be restored (e.g. deleted files).
    @discardableResult
    public func copyToPasteboard(_ item: ClipboardItem) -> Bool {
        let pbItem = NSPasteboardItem()
        switch item.type {
        case .text:
            guard let text = item.contentText else { return false }
            pbItem.setString(text, forType: .string)
        case .url:
            guard let text = item.contentText else { return false }
            pbItem.setString(text, forType: .string)
            pbItem.setString(text, forType: .URL)
        case .richText:
            guard let text = item.contentText else { return false }
            if let rtf = item.rtfData { pbItem.setData(rtf, forType: .rtf) }
            pbItem.setString(text, forType: .string)
        case .image:
            guard let png = imageData(for: item) else { return false }
            pbItem.setData(png, forType: .png)
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                pbItem.setData(tiff, forType: .tiff)
            }
        case .file:
            let urls = item.fileURLs
            guard !urls.isEmpty, item.missingFilePaths.isEmpty else { return false }
            pasteboard.clearContents()
            guard pasteboard.writeObjects(urls.map { $0 as NSURL }) else { return false }
            markRestored(item)
            return true
        }
        if item.isSensitive {
            pbItem.setData(Data(), forType: Self.concealedType)
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([pbItem]) else { return false }
        markRestored(item)
        return true
    }

    private func markRestored(_ item: ClipboardItem) {
        // Our own write must not be recorded as a new capture.
        lastChangeCount = pasteboard.changeCount
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var restored = items.remove(at: index)
        restored.timestamp = environment.now()
        items.insert(restored, at: 0)
        saveHistory()
    }

    public func imageData(for item: ClipboardItem) -> Data? {
        if let name = item.imageFileName, let data = storage.imageData(named: name) { return data }
        return item.imagePNGData
    }

    public func thumbnail(for item: ClipboardItem, maxPixelSize: Int = 96) -> NSImage? {
        if let name = item.imageFileName { return storage.thumbnail(named: name, maxPixelSize: maxPixelSize) }
        return item.imagePNGData.flatMap(NSImage.init(data:))
    }

    public func togglePin(_ itemID: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == itemID }) else { return }
        items[idx].isPinned.toggle()
        applyLimitsAndSave()
    }

    public func deleteItem(_ itemID: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == itemID }) else { return }
        let item = items.remove(at: idx)
        if let name = item.imageFileName { storage.deleteImage(named: name) }
        saveHistory()
    }

    /// Removes every unpinned item. Pinned items are kept.
    public func clearAll() {
        let removed = items.filter { !$0.isPinned }
        items.removeAll { !$0.isPinned }
        for item in removed {
            if let name = item.imageFileName { storage.deleteImage(named: name) }
        }
        saveHistory()
    }

    /// Deletes all history, including pinned items and stored images.
    public func wipeEverything() {
        items.removeAll()
        storage.eraseEverything()
        saveHistory()
    }

    public func addExcludedApp(bundleID: String) {
        let trimmed = bundleID.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        excludedBundleIDs.insert(trimmed)
    }

    public func removeExcludedApp(bundleID: String) {
        excludedBundleIDs.remove(bundleID)
    }

    public var imageStorageBytes: Int64 {
        items.filter { $0.type == .image }.reduce(Int64(0)) { $0 + $1.byteSize }
    }

    // MARK: - Search

    /// Shared filtering for the page, picker and menu bar. All search terms must match.
    nonisolated public static func filter(
        _ items: [ClipboardItem],
        query: String,
        type: ClipboardContentType? = nil,
        pinnedOnly: Bool = false
    ) -> [ClipboardItem] {
        let terms = query.lowercased().split(whereSeparator: \.isWhitespace).map(String.init)
        return items.filter { item in
            if pinnedOnly && !item.isPinned { return false }
            if let type, item.type != type { return false }
            guard !terms.isEmpty else { return true }
            let haystack = item.searchableText
            return terms.allSatisfy { haystack.contains($0) }
        }
    }

    // MARK: - Sensitive Content Heuristics

    public func checkSensitive(text: String) -> Bool {
        Self.detectSensitive(text: text)
    }

    /// Pattern-based only; it cannot recognise arbitrary passwords.
    nonisolated public static func detectSensitive(text: String) -> Bool {
        let lower = text.lowercased()

        if text.hasPrefix("Bearer ") || lower.contains("private_key") || lower.contains("password=")
            || (text.contains("-----BEGIN") && text.contains("PRIVATE KEY")) {
            return true
        }

        let tokenPrefixes = ["ghp_", "gho_", "ghs_", "github_pat_", "sk_live_", "rk_live_", "sk-", "xoxb-", "xoxp-", "AKIA", "AIza"]
        if !text.contains(where: \.isWhitespace), text.count >= 16,
           tokenPrefixes.contains(where: { text.hasPrefix($0) }) {
            return true
        }

        // Card-number-like groups of digits.
        let digitsOnly = text.filter(\.isNumber)
        if (13...19).contains(digitsOnly.count) && (text.contains("-") || text.contains(" "))
            && text.allSatisfy({ $0.isNumber || $0 == "-" || $0 == " " }) {
            return true
        }

        return false
    }

    // MARK: - Persistence

    private func saveHistory() {
        guard hasLoadedHistory else { return }
        storage.saveHistory(items)
    }

    private func loadHistory() {
        var loaded = storage.loadHistory()
        var migrated = false
        for index in loaded.indices {
            // v1 stored PNG bytes inline in the JSON file.
            if let png = loaded[index].imagePNGData, loaded[index].imageFileName == nil,
               let name = storage.writeImage(png, id: loaded[index].id) {
                loaded[index].imageFileName = name
                loaded[index].imagePNGData = nil
                migrated = true
            }
            if loaded[index].contentHash == nil {
                loaded[index].contentHash = Self.legacyHash(for: loaded[index], storage: storage)
                migrated = true
            }
        }
        items = loaded.sorted { $0.timestamp > $1.timestamp }
        hasLoadedHistory = true
        storage.removeOrphanedImages(keeping: Set(items.compactMap(\.imageFileName)))
        let countBefore = items.count
        applyLimits()
        if migrated || items.count != countBefore {
            saveHistory()
        }
    }

    private static func legacyHash(for item: ClipboardItem, storage: ClipboardStorage) -> String {
        switch item.type {
        case .file:
            return ClipboardItem.hash(type: .file, parts: (item.filePaths ?? []).map { Data($0.utf8) })
        case .image:
            let data = item.imageFileName.flatMap(storage.imageData(named:)) ?? item.imagePNGData ?? Data(item.id.uuidString.utf8)
            return ClipboardItem.hash(type: .image, parts: [data])
        case .text, .url, .richText:
            var parts = [Data((item.contentText ?? item.preview).utf8)]
            if let rtf = item.rtfData { parts.append(rtf) }
            return ClipboardItem.hash(type: item.type, parts: parts)
        }
    }
