import Foundation

public struct CleanupFileItem: Identifiable, Sendable {
    public var id: String { path }
    public var path: String
    public var name: String
    public var sizeBytes: UInt64
    public var modifiedDate: Date?
    public var isSafe: Bool
    
    public init(path: String, name: String, sizeBytes: UInt64, modifiedDate: Date? = nil, isSafe: Bool = true) {
        self.path = path
        self.name = name
        self.sizeBytes = sizeBytes
        self.modifiedDate = modifiedDate
        self.isSafe = isSafe
    }
}

public enum CleanupCategoryType: String, CaseIterable, Sendable {
    case userCaches = "User Application Caches"
    case tempFiles = "Temporary Files"
    case diagnosticLogs = "Diagnostic & Crash Logs"
    case xcodeDerivedData = "Xcode DerivedData"
    case trash = "Trash"
    
    public var defaultSelected: Bool {
        switch self {
        case .userCaches, .tempFiles, .diagnosticLogs, .xcodeDerivedData:
            return true
        case .trash:
            return false // Trash requires explicit confirmation
        }
    }
    
    public var icon: String {
        switch self {
        case .userCaches: return "sparkles"
        case .tempFiles: return "clock.arrow.circlepath"
        case .diagnosticLogs: return "doc.text.magnifyingglass"
        case .xcodeDerivedData: return "hammer"
        case .trash: return "trash"
        }
    }
    
    public var explanation: String {
        switch self {
        case .userCaches:
            return "Reclaimable cached data generated by applications in ~/Library/Caches. Applications will recreate cache entries as needed. Note: Clearing may temporarily slow first app launch."
        case .tempFiles:
            return "Temporary session files stored in standard user temporary locations that are no longer locked by active processes."
        case .diagnosticLogs:
            return "Old crash logs, diagnostic reports, and system telemetry records stored in ~/Library/Logs."
        case .xcodeDerivedData:
            return "Intermediates and build products in ~/Library/Developer/Xcode/DerivedData. Safe to remove; Xcode rebuilds upon project build."
        case .trash:
            return "Files currently located in your user Trash (~/.Trash). Deletion is irreversible."
        }
    }
}

public struct CleanupCategory: Identifiable, Sendable {
    public var id: CleanupCategoryType { type }
    public var type: CleanupCategoryType
    public var title: String { type.rawValue }
    public var icon: String { type.icon }
    public var explanation: String { type.explanation }
    public var path: String
    public var estimatedSizeBytes: UInt64
    public var fileCount: Int
    public var isSelected: Bool
    public var files: [CleanupFileItem]
    
    public init(
        type: CleanupCategoryType,
        path: String,
        estimatedSizeBytes: UInt64 = 0,
        fileCount: Int = 0,
        isSelected: Bool = false,
        files: [CleanupFileItem] = []
    ) {
        self.type = type
        self.path = path
        self.estimatedSizeBytes = estimatedSizeBytes
        self.fileCount = fileCount
        self.isSelected = isSelected
        self.files = files
    }
}

public struct CleanupResult: Sendable {
    public var totalFreedBytes: UInt64
    public var deletedCount: Int
    public var failedCount: Int
    public var isDryRun: Bool
    public var errors: [String]
    
    public init(totalFreedBytes: UInt64 = 0, deletedCount: Int = 0, failedCount: Int = 0, isDryRun: Bool = false, errors: [String] = []) {
        self.totalFreedBytes = totalFreedBytes
        self.deletedCount = deletedCount
        self.failedCount = failedCount
        self.isDryRun = isDryRun
        self.errors = errors
    }
}
